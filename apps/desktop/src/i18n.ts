export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const message = (isWindows ? windowsOverrides[locale][key] : undefined) ?? messages[key];
  const template = typeof message === "string" ? message : pluralRules.select(Number(params?.count ?? 0)) === "one" ? message.one : message.other;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => name in params ? String(params[name]) : match);
}

/// 사전에 없을 수 있는 동적 키(세션 상태·인증 근거)를 안전하게 찾는다.
export function lookup(prefix: "session.state" | "verification", value: string): string | null {
  const key = `${prefix}.${value}` as MessageKey;
  return key in messages ? t(key) : null;
}

/// 서비스가 내려주는 한도 라벨의 기간 단어(`5시간`·`주간`·`모델 한도`)를 표시 언어로 바꾼다.
/// 라벨 원문은 저장값과 서비스 메시지에 그대로 쓰이므로 화면에서만 바꾼다.
export function limitLabel(label: string): string {
  return label
    .replace(/5시간/g, t("limit.period.fiveHour"))
    .replace(/주간/g, t("limit.period.weekly"))
    .replace(/모델 한도/g, t("limit.period.model"));
}

/// 호스트 연결 안내 한 줄(서비스는 키와 값만 보낸다). 모르는 키는 빈 문자열로 두어 오래된 서비스와도 화면이 깨지지 않게 한다.
export function hostNote(note: { key: string; params?: Record<string, string> }): string {
  const key = `hosts.note.${note.key}` as MessageKey;
  if (!(key in messages)) return "";
  const params = { ...note.params };
  if (params.layer) {
    const layer = `hosts.layer.${params.layer}` as MessageKey;
    if (layer in messages) params.layer = t(layer);
  }
  return t(key, params);
}

/// 준비 단계 실패 안내. 아는 코드는 표시 언어로 바꾸고, 모르는 코드는 서비스가 보낸 문장을 그대로 보여 준다.
export function setupNotice(notice: { code: string; message: string; params?: Record<string, string> }): string {
  const key = `setup.notice.${notice.code}` as MessageKey;
  if (!(key in messages)) return notice.message;
  return t(key, notice.params);
}

/// 서비스가 자동 발견 계정에 붙이는 `· 기본 프로필` 표기를 표시 언어로 바꾼다. 저장된 라벨은 바꾸지 않는다.
export function accountLabel(label: string): string {
  return label.replace(/기본 프로필/g, t("account.defaultProfile"));
}
