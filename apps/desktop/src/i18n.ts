/// UI 문자열 사전. 설정에서 고른 언어가 있으면 그 언어를, 없으면 OS 선호 언어가 한국어(`ko*`)면 한국어, 인도네시아어(`id*`, 예전 `in*`)면 인도네시아어, 아니면 영어를 쓴다.
/// 서비스·어댑터가 보내는 문장(account.reason, notice, ApiError.message, 배정 사유)은 서버 텍스트 그대로 보여 준다.
export type Locale = "en" | "ko" | "id";

/// 설정에서 고른 언어. 네이티브(`ui-settings.json`)가 기준이고, 화면은 시작 직후 읽을 수 있게 여기에도 둔다.
export const LANGUAGE_KEY = "ojak.language";
export type LanguageChoice = "system" | Locale;

/** OS·저장 태그에서 UI 언어를 고른다. 인도네시아어의 예전 ISO 코드 `in`도 받는다. */
export function localeFromTag(tag: string | undefined): Locale {
  const value = tag?.toLowerCase() ?? "";
  if (value.startsWith("ko")) return "ko";
  if (value.startsWith("id") || value.startsWith("in")) return "id";
  return "en";
}

function detectLocale(): Locale {
  try {
    const chosen = localStorage.getItem(LANGUAGE_KEY);
    if (chosen === "ko" || chosen === "en" || chosen === "id") return chosen;
  } catch { /* 저장소를 못 읽으면 시스템 언어를 쓴다. */ }
  if (typeof navigator === "undefined") return "en";
  const preferred = navigator.languages?.length ? navigator.languages : [navigator.language];
  return localeFromTag(preferred[0]);
}

